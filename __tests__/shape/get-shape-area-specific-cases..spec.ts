    function testIt(
            filename: string,
            expectedAreas: number[]) {

        const { bezierLoops } = getPathFromFile(filename);

        // one exact signed area per loop (loops are not necessarily Jordan
        // curves - see the note in `getShapeArea2`)
        const areas = bezierLoops.map(getShapeArea$);
        const ddAreas = bezierLoops.map(ddGetShapeArea).map(a => a[1]);

        const expMax = ceil(log2(getMaxCoordinate(bezierLoops)));
        const ulpPower = expMax - 53;
        const ulp = 2**ulpPower;
        const ulpPerEps = ulp/eps;

        for (let i=0; i<areas.length; i++) {
            const area = areas[i];
            const ddArea = ddAreas[i];

            // note: `ulp` of original shape; squared since we're working with areas
            const maxAllowedUlpError = (2**6)**2;
            expect(area).toBeNearly([maxAllowedUlpError*ulpPerEps], ddArea, `${filename}: `)

            expect(area).toBeNearly([maxAllowedUlpError*ulpPerEps], expectedAreas[i], `${filename}: `);
        }
    }
